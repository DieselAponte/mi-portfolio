-- -----------------------------------------------------------------------------
-- 3. AUTO-UPDATE TRIGGER FUNCTION
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOR tbl IN
        SELECT unnest(ARRAY[
            'blog_articles',
            'projects',
            'home_services',
            'home_cases_of_study',
            'experience_certifications',
            'experience_carousel_items',
            'technologies',
            'topics',
            'nivel_publicacion',
            'education_details',
            'project_details',
            'professional_exp_details',
            'publication_responsibilities',
            'publication_achievements',
            'experience_modules',
            'experience_slides',
            'tech_bubbles'
        ])
    LOOP
        EXECUTE format(
            'DROP TRIGGER IF EXISTS trg_%I_updated_at ON public.%I;
             CREATE TRIGGER trg_%I_updated_at
                BEFORE UPDATE ON public.%I
                FOR EACH ROW
                EXECUTE FUNCTION public.set_updated_at();',
            tbl, tbl, tbl, tbl
        );
    END LOOP;
END;
$$;

